#!/usr/bin/env python3
"""Write a large HAMR write run in VAMPIRE's file formats, without running VAMPIRE, for the scale tests.

The film is a sheet of square-lattice atoms cut into rectangular grains with one non-magnetic column between them. A
grain's state is a known function of time: |m| dips as the laser centre passes and it then takes the direction of its
bit, except for every wrong_every-th grain, which keeps its old direction. Every file is written a piece at a time, so
any size fits in memory. Not physics: only the numbers the reducer and viewer have to carry unchanged.

    tests/make_large.py OUT --size 2000 60 --atoms 100e6 --grains 10000 --frames 100000 --snapshots 5
"""
import argparse
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from hamrvis import vampire as vp  # noqa: E402

PITCH = 2.5        # A, in x, y and z
WRONG_EVERY = 10
DIP = 0.95         # |m| at the moment the laser passes is 1 - DIP
CHUNK = 1 << 22


def write_input(out, X, Y, Z, n_bits, track, bit, nps, grain_rate, out_rate, snap_rate):
    text = f"""create:crystal-structure = sc
create:granular-film
dimensions:unit-cell-size = {PITCH} !A
dimensions:system-size-x = {X} !nm
dimensions:system-size-y = {Y} !nm
dimensions:system-size-z = {Z} !nm
material:file = m.mat
sim:minimum-temperature = 300
sim:maximum-temperature = 700
sim:time-step = 1.0 !fs
sim:minimum-applied-field-strength = 0.0
sim:maximum-applied-field-strength = 1.0
sim:applied-field-unit-vector = 0,0,1
sim:program = hamr-simulation
sim:integrator = llg-heun
hamr:laser-FWHM-x = 30 !nm
hamr:laser-FWHM-y = 30 !nm
hamr:head-speed = 50 !m/s
hamr:head-field-x = 30 !nm
hamr:head-field-y = 30 !nm
hamr:NPS = {nps} !nm
hamr:bit-size = {bit} !nm
hamr:track-size = {track} !nm
hamr:number-of-bits = {n_bits}
hamr:bit-sequence-type = single-tone-predefined
output:output-rate = {out_rate}
output:column-headers
output:real-time
output:temperature
output:applied-field-strength
output:magnetisation
grain:real-time
grain:magnetisation
grain:output-rate = {grain_rate}
config:atoms
config:output-format = binary
config:atoms-output-rate = {snap_rate}
"""
    open(os.path.join(out, "input"), "w").write(text)
    open(os.path.join(out, "m.mat"), "w").write(
        "material:num-materials=2\nmaterial[1]:material-name=film\nmaterial[1]:atomic-spin-moment=2.0 !muB\n"
        "material[2]:material-name=gap\nmaterial[2]:non-magnetic=keep\n")


def header(title):
    return f"#{'-' * 60}\n# {title}\n#   version    : generated by tests/make_large.py\n#{'-' * 60}\n"


class Film:
    def __init__(self, X, Y, atoms, grains):
        self.nx, self.ny = int(round(X * 10 / PITCH)), int(round(Y * 10 / PITCH))
        self.nz = max(1, int(round(atoms / (self.nx * self.ny))))
        self.n = self.nx * self.ny * self.nz
        self.gx = max(1, int(round(np.sqrt(grains * X / Y))))
        self.gy = max(1, int(round(grains / self.gx)))
        self.nG = self.gx * self.gy
        self.Z = self.nz * PITCH / 10

    def atoms(self, a, b):
        """ix, iy, iz, grain, magnetic of atoms a..b."""
        i = np.arange(a, b, dtype=np.int64)
        iz, rest = np.divmod(i, self.nx * self.ny)
        iy, ix = np.divmod(rest, self.nx)
        tx, ty = ix * self.gx // self.nx, iy * self.gy // self.ny
        # the last column of a grain is the gap
        gap = ((ix + 1) * self.gx // self.nx != tx) | ((iy + 1) * self.gy // self.ny != ty)
        return ix, iy, iz, tx + self.gx * ty, ~gap

    def centres(self):
        """Grain centres of the magnetic columns (nm), and magnetic atoms per grain."""
        cols = [np.arange(self.nx) * self.gx // self.nx, np.arange(self.ny) * self.gy // self.ny]
        res, size = [], []
        for axis, (c, g, n) in enumerate(zip(cols, (self.gx, self.gy), (self.nx, self.ny))):
            keep = (np.arange(1, n + 1) * g // n) == c                 # not the gap column
            res.append(np.bincount(c[keep], np.arange(n)[keep], minlength=g) / np.maximum(np.bincount(c[keep], minlength=g), 1) * PITCH / 10)
            size.append(np.bincount(c[keep], minlength=g))
        x = np.tile(res[0], self.gy)
        y = np.repeat(res[1], self.gx)
        return x, y, np.tile(size[0], self.gy) * np.repeat(size[1], self.gx) * self.nz


class State:
    """Direction and |m| of every grain at any step: the known answer."""

    def __init__(self, h, x, y):
        self.h, self.w = h, h.sigma_x / h.step_nm
        t = h.track_of(y)
        b = np.floor((x + 0.0) / h.BL).astype(int)
        seq = np.asarray(h.sequence)
        inside = (b >= 0) & (b < h.bits_per_track)
        want = np.where(inside, seq[np.clip(t * h.bits_per_track + b, 0, len(seq) - 1)], 0)
        want = np.where(np.arange(len(x)) % WRONG_EVERY == WRONG_EVERY - 1, 0, want) * h.field_uz
        self.after = np.where(want == 0, 1.0, np.sign(want))           # starts +z; 0: keeps it
        self.passes = h.eq + t * h.nt + np.rint((x + h.BL / 2 + h.NPS) / h.step_nm) - 1

    def at(self, step):
        dip = DIP * np.exp(-(((step - self.passes) / self.w) ** 2))
        return np.where(step > self.passes, self.after, 1.0), np.round(1 - dip, 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--size", type=float, nargs=2, default=[2000, 60], metavar=("X", "Y"), help="film size (nm)")
    ap.add_argument("--atoms", type=float, default=1e8)
    ap.add_argument("--grains", type=int, default=10000)
    ap.add_argument("--frames", type=int, default=100000)
    ap.add_argument("--snapshots", type=int, default=5)
    ap.add_argument("--files", type=int, default=1, help="data files per snapshot (as file-per-process output)")
    ap.add_argument("--track", type=float, help="track width (nm; default: one track on the film, or 28 for a tall film)")
    ap.add_argument("--bit", type=float, default=6.0, help="bit length (nm)")
    a = ap.parse_args()
    make(a.out, *a.size, a.atoms, a.grains, a.frames, a.snapshots, a.files, a.track, a.bit)


def make(out, X, Y, atoms, grains, frames, snapshots, files=1, track=None, bit=6.0):
    os.makedirs(out, exist_ok=True)
    t0 = time.time()
    F = Film(X, Y, atoms, grains)
    track = track or (Y - 2 if Y <= X else 28.0)
    nps = 5.0
    bits_per_track, tracks = int((X - 0.1) // bit), max(1, int((Y - 0.1) // track))
    write_input(out, X, Y, F.Z, bits_per_track * tracks, track, bit, nps, 1, 1, 1)
    h = vp.Hamr(out)
    total = h.eq + h.laser_steps
    grain_rate = max(1, total // frames)
    snap_rate = max(1, (total - 1) // max(snapshots - 1, 1) // grain_rate) * grain_rate    # VAMPIRE: step k * rate + 1
    write_input(out, X, Y, F.Z, bits_per_track * tracks, track, bit, nps, grain_rate, grain_rate, snap_rate)
    with open(os.path.join(out, "log"), "w") as f:
        f.write("05-11-2026 [12:00:00] Logfile opened\n")
        f.writelines(f"05-11-2026 [12:00:00] Written bit {b + 1} : bit {b + 1} on track 1\n" for b in range(bits_per_track))
        f.write("05-11-2026 [12:00:00] Head position at end of track 1 : 0 nm, 0 nm\n")
    h = vp.Hamr(out)
    x, y, mags = F.centres()
    S = State(h, x, y)
    with open(os.path.join(out, "grain-coordinates.txt"), "w") as f:
        f.write(f"#{'-' * 60}\n# Grain coordinate file for vampire\n# Number of grains: {F.nG}\n")
        for g in range(F.nG):
            f.write(f"{g} {x[g] * 10:.6f} {y[g] * 10:.6f} {mags[g]} {2.0 * mags[g]}\n")
    # one string per (direction, |m| in 1/1000): the grain block of a frame is a join, not 4 x grains number formats
    table = np.array([f"0 0 {d} {m / 1000:.3f}" for d in (-1, 1) for m in range(1001)], dtype=object)
    with open(os.path.join(out, "grain.txt"), "w") as g, open(os.path.join(out, "output"), "w") as o:
        o.write(header("Output file for vampire simulation"))
        o.write("Real_time Temperature B_applied film_M_norm_x film_M_norm_y film_M_norm_z film_M_norm_l\n")
        for k in range(1, total // grain_rate + 1):
            step = k * grain_rate
            d, m = S.at(step)
            t = step * h.dt
            g.write(f"{t:.12g} " + " ".join(table[(d > 0) * 1001 + np.rint(m * 1000).astype(int)].tolist()) + "\n")
            w = mags / mags.sum()
            ml = float((w * m).sum())
            mz = float((w * m * d).sum()) / max(ml, 1e-9)
            o.write(f"{t:.12g} {float(h.temperature(x[0], y[0], step)):.5g} {float(h.field(step)):.5g} 0 0 {mz:.6f} {ml:.6f}\n")
            if k % 10000 == 0:
                print(f"  frame {k} ({time.time() - t0:.0f} s)", flush=True)
    edges = np.linspace(0, F.n, files + 1).astype(np.int64)
    names = [f"atoms-coords-{i:05d}.data" for i in range(files)] if files > 1 else ["atoms-coords.data"]
    with open(os.path.join(out, "atoms-coords.meta"), "w") as f:
        f.write(f"#{'-' * 58}\n# Atomistic coordinates configuration file for vampire V5+\n#{'-' * 58}\nFormat: binary\n"
                f"Number of atoms: {F.n}\nNumber of materials: 2\n0\t2\tH\tfilm\n1\t0\tH\tgap\n"
                f"Number of coord files: {files}\n" + "\n".join(names) + "\nGrain data: true\n")
    for name, a, b in zip(names, edges, edges[1:]):
        with open(os.path.join(out, name), "wb") as f:
            np.array([b - a], np.uint64).tofile(f)
            for part in ("type", "category", "xyz", "grain"):
                for c in range(a, b, CHUNK):
                    ix, iy, iz, gr, mag = F.atoms(c, min(b, c + CHUNK))
                    if part == "type":
                        (~mag).astype(np.int32).tofile(f)
                    elif part == "category":
                        np.zeros(len(ix), np.int32).tofile(f)
                    elif part == "xyz":
                        (np.stack([ix, iy, iz], 1) * PITCH).astype(np.float64).tofile(f)
                    else:
                        gr.astype(np.int32).tofile(f)
    print(f"  coordinates done ({time.time() - t0:.0f} s)", flush=True)
    for s in range(snapshots):
        step = min(s * snap_rate + 1, total)
        d, m = S.at(step)
        names = [f"spins-{i:05d}-{s:08d}.data" for i in range(files)] if files > 1 else [f"spins-{s:08d}.data"]
        with open(os.path.join(out, f"spins-{s:08d}.meta"), "w") as f:
            f.write(f"#{'-' * 54}\n# Atomistic spin configuration file for vampire v5+\n#{'-' * 54}\nTime: {step * h.dt:.12g}\n"
                    f"Number of spin files: {files}\n" + "\n".join(names) + "\n")
        for name, a, b in zip(names, edges, edges[1:]):
            with open(os.path.join(out, name), "wb") as f:
                np.array([b - a], np.uint64).tofile(f)
                for c in range(a, b, CHUNK):
                    ix, iy, iz, gr, mag = F.atoms(c, min(b, c + CHUNK))
                    # every atom of a grain: m_z = direction x |m|; x alternates so the grain's mean x is near 0
                    mz, sxy = d[gr] * m[gr], np.sqrt(1 - m[gr] ** 2)
                    np.stack([sxy * (1 - 2 * ((ix + iy + iz) % 2)), np.zeros(len(ix)), mz], 1).tofile(f)
        print(f"  snapshot {s} done ({time.time() - t0:.0f} s)", flush=True)
    print(f"{out}: {F.n} atoms, {F.nG} grains, {total // grain_rate} frames, {snapshots} snapshots, "
          f"{h.n_tracks} x {h.bits_per_track} bits, {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
